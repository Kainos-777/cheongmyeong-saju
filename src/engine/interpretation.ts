export function getIljuInterpretation(
  dayGapjaIndex: number,
  yongshin: { primary: ElementKey; secondary: ElementKey; avoidElement: ElementKey }
): SajuInterpretation {
  const entry = SIXTY_GAPJA[((dayGapjaIndex % 60) + 60) % 60];
  const profile = SIXTY_ILJU_PROFILES[entry.hangul] ?? SIXTY_ILJU_PROFILES['갑자'];

  const primaryMeta = ELEMENT_META[yongshin.primary];
  const secondaryMeta = ELEMENT_META[yongshin.secondary];

  const luckyElements: ElementKey[] = [yongshin.primary, yongshin.secondary];
  const luckyColors = [
    {
      name: primaryMeta.luckyColors[0].name,
      hex: primaryMeta.luckyColors[0].hex,
      element: yongshin.primary,
    },
    {
      name: primaryMeta.luckyColors[1].name,
      hex: primaryMeta.luckyColors[1].hex,
      element: yongshin.primary,
    },
    {
      name: secondaryMeta.luckyColors[0].name,
      hex: secondaryMeta.luckyColors[0].hex,
      element: yongshin.secondary,
    },
  ];

  const luckyDirection = `${primaryMeta.directionKo} · 보조 ${secondaryMeta.directionKo}`;
  const luckyNumbers = Array.from(
    new Set([...primaryMeta.luckyNumbers, ...secondaryMeta.luckyNumbers])
  );

  return {
    iljuTitle: `${entry.hangul}일주 (${entry.hanja}日柱)`,
    iljuAnimal: profile.iljuAnimal,
    archetype: profile.archetype,
    coreSummary: profile.coreSummary,
    personalityStrengths: profile.personalityStrengths,
    growthChallenges: profile.growthChallenges,
    careerDesignStyle: profile.careerDesignStyle,
    loveStyle: profile.loveStyle,
    wealthStyle: profile.wealthStyle,
    healthAdvice: profile.healthAdvice,
    luckyElements,
    luckyColors,
    luckyDirection,
    luckyNumbers,
  };
}
